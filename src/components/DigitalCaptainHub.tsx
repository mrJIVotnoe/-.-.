  const translateNode = (node: React.ReactNode): React.ReactNode => {
    if (!node) return node;
    if (typeof node === 'string') {
      return tLocal(node);
    }
    if (typeof node === 'number') {
      return node;
    }
    if (Array.isArray(node)) {
      return node.map((child, index) => <React.Fragment key={index}>{translateNode(child)}</React.Fragment>);
    }
    if (React.isValidElement(node)) {
      const element = node as React.ReactElement<any>;
      let propsCopy = { ...element.props };
      let changed = false;

      if (propsCopy.placeholder && typeof propsCopy.placeholder === 'string') {
        propsCopy.placeholder = tLocal(propsCopy.placeholder);
        changed = true;
      }
      if (propsCopy.title && typeof propsCopy.title === 'string') {
        propsCopy.title = tLocal(propsCopy.title);
        changed = true;
      }

      if (propsCopy.children) {
        propsCopy.children = React.Children.map(propsCopy.children, child => translateNode(child));
        changed = true;
      }

      if (changed) {
        return React.cloneElement(element, propsCopy);
      }
    }
    return node;
  };

